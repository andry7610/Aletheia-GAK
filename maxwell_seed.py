# -*- coding: utf-8 -*-
"""
maxwell_seed — канонические уравнения Максвелла для Гиппокампа (v1.3).

Пять законов: полный квадрат Максвелла (4) + стационарное приближение
Ампера, сохранённое для обратной совместимости со старыми тестами (v1.2).

v1.3: посажен полный закон Ампера—Максвелла с током смещения.
Уравнение непрерывности теперь ВЫВОДИМО из полного Ампера и Гаусса
через слой derivation.py — тест test_continuity_derived_from_ampere.

Символы полей: E, B, j, rho — добавляются в quantities при посеве.
"""
import sympy as sp

MAXWELL_FIELDS = [
    ("E", "V/m", "Напряжённость электрического поля (вектор)"),
    ("B", "T", "Магнитная индукция (вектор)"),
    ("j", "A/m**2", "Плотность тока (вектор)"),
    ("rho", "C/m**3", "Объёмная плотность заряда"),
]

MAXWELL_LAWS = {
    "faraday_law": {
        "lhs": "rot(E) + ddt(B)",
        "rhs": "0",
        "description": "Закон Фарадея: rot E = -dB/dt",
    },
    "gauss_electric": {
        "lhs": "div(E)",
        "rhs": "rho/epsilon_0",
        "description": "Теорема Гаусса для электрического поля",
    },
    "ampere_maxwell": {
        "lhs": "rot(B) - mu_0*(j + epsilon_0*ddt(E))",
        "rhs": "0",
        "description": "Закон Ампера—Максвелла (полная форма, с током смещения)",
    },
    "ampere_no_displacement": {
        "lhs": "rot(B)",
        "rhs": "mu_0*j",
        "description": "Закон Ампера, СТАЦИОНАРНОЕ ПРИБЛИЖЕНИЕ (без тока смещения). "
                       "Не использовать вместе с уравнением непрерывности: "
                       "противоречит ему для нестационарных полей",
    },
    "gauss_magnetic": {
        "lhs": "div(B)",
        "rhs": "0",
        "description": "Теорема Гаусса для магнитного поля: нет магнитных зарядов",
    },
}


def get_maxwell_laws() -> list[tuple[str, str, str]]:
    """Список (имя, lhs, rhs) для add_law."""
    return [(name, law["lhs"], law["rhs"])
            for name, law in MAXWELL_LAWS.items()]
